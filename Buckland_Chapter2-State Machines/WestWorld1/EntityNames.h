//==============================================================================================
//【文件说明】EntityNames.h —— "角色编号 ↔ 角色名字"对照表
//
//【这个文件是干什么的?】
//  游戏里每个角色(术语叫"实体"entity)都要有一个整数编号(ID),
//  由基类 BaseGameEntity 负责登记(见 BaseGameEntity.h/.cpp)。
//  但屏幕上打印 "0: xxx" 没人知道 0 是谁,所以本文件做两件事:
//    1) 用枚举给角色定编号:ent_Miner_Bob = 0(矿工鲍勃)、ent_Elsa = 1(艾尔莎);
//    2) 提供 GetNameOfEntity() 函数:输入编号,返回角色的名字字符串,
//       打印台词时就能显示成 "Miner Bob: ...(台词)"。
//
//【谁在使用这个文件?】
//  1. main.cpp —— 创建矿工时把 ent_Miner_Bob 当编号传给构造函数:
//                 Miner miner(ent_Miner_Bob);
//  2. MinerOwnedStates.cpp —— 打印台词前调用 GetNameOfEntity(pMiner->ID()),
//                 把矿工编号翻译成 "Miner Bob" 显示;
//  3. BaseGameEntity.h/.cpp —— 负责登记编号(不含本文件,但接收 main.cpp
//                 从这里传过去的编号)。
//  注:ent_Elsa 在 WestWorld1 里只是占位、尚未使用——艾尔莎是矿工 Bob 的妻子,
//      在本书后续示例(WestWorldWithWoman / WestWorldWithMessaging)才会登场。
//==============================================================================================

// 包含保护(原理详解见 Locations.h):防止本文件被重复包含。
#ifndef NAMES_H
#define NAMES_H

// <string>:C++ 标准库的"字符串"头文件,尖括号表示到编译器的标准目录里找。
// std::string 是标准库提供的字符串类型,下面 GetNameOfEntity() 的返回值就是它。
#include <string>

//--------------------------------------------------------------------------------
//【匿名枚举】注意 enum 后面没有写类型名——这不是为了造新类型,
// 只是为了得到一组"有名字的整数常量":
//   ent_Miner_Bob = 0 —— "ent" 是 entity(实体)的缩写,这是矿工 Bob 的编号;
//   ent_Elsa     = 1 —— 艾尔莎的编号(枚举项不赋值时自动在上一个的基础上加 1)。
// 中间留一个空行只是原作者的排版习惯,把"已登场的"和"将登场的"角色隔开。
//--------------------------------------------------------------------------------
enum 
{
  ent_Miner_Bob,

  ent_Elsa
};

//--------------------------------------------------------------------------------
//【把编号翻译成名字的函数】
//   inline      —— "内联":建议编译器把函数体直接展开复制到调用处,
//                  省去函数调用的开销;更重要的原因是:在头文件里"定义"
//                  (而不是只声明)函数时必须加 inline,否则多个 .cpp 包含
//                  本文件后,同一个函数会出现多份定义,链接时报"重复定义"。
//   std::string —— 返回类型:标准库命名空间 std 里的字符串类型。
//                  "std::" 是"命名空间::名字"的限定写法,意思是"std 那个
//                  命名空间里的 string",防止与别人同名的 string 混淆。
//   (int n)     —— 参数:调用者传进来一个整数编号,函数内用 n 这个名字使用它。
//--------------------------------------------------------------------------------
inline std::string GetNameOfEntity(int n)
{
  // switch(变量) —— 多路分支:拿 n 的值与下面每个 case 的值逐个比较,
  // 命中哪个就执行哪一段,遇到 return 就结束整个函数。
  switch(n)
  {
  // 如果编号是 ent_Miner_Bob(即 0):
  case ent_Miner_Bob:

    // return —— 结束函数,并把后面的值作为结果送回给调用者。
    // 这里返回字符串字面量 "Miner Bob"(双引号括起来的一串字符)。
    return "Miner Bob";

  // 如果编号是 ent_Elsa(即 1):
  case ent_Elsa:
    
    return "Elsa"; 

  // default —— 兜底分支:上面所有 case 都没命中时执行。
  // 将来若出现没登记过名字的新编号,返回 "UNKNOWN!" 而不是空白。
  default:

    return "UNKNOWN!";
  }
}

#endif