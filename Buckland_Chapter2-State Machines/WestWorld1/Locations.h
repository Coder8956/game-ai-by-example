//==============================================================================================
//【文件说明】Locations.h —— 游戏世界的"地点清单"
//
//【这个文件是干什么的?】
//  矿工 Bob 生活的"西部世界"里共有 4 个地点:小屋、金矿、银行、酒吧。
//  本文件把这些地点定义成一个"枚举"(enum),给每个地点一个正式的名字,
//  供整个工程共用。以后代码里直接写 goldmine(金矿)这种一目了然的名字,
//  而不是写 0、1、2 这种过几天就没人记得含义的"魔法数字"。
//
//【谁在使用这个文件?】(= 哪些文件用 #include 包含了它)
//  1. Miner.h               —— 矿工身上有个"当前地点"成员 m_Location,
//                              它的类型 location_type 就定义在本文件里;
//  2. Miner.cpp             —— 矿工出生时被初始化在小屋(m_Location(shack));
//  3. MinerOwnedStates.cpp  —— 各个状态类会判断矿工在哪(Location() != goldmine)、
//                              并把矿工搬到新地点(ChangeLocation(bank));
//  4. main.cpp              —— 也包含了本文件,但主程序本身没直接用到地点(无害的习惯写法)。
//
//【C++ 小课堂:头文件(.h)与源文件(.cpp)的分工】
//  .h(头文件,head):像"目录/说明书",写"有什么"(声明),供别的文件复制引用;
//  .cpp(源文件)   :写"具体怎么做"(实现)。
//  编译时:每个 .cpp 连同它包含的所有 .h 一起编译成一个目标文件(.obj),
//  最后把所有目标文件"链接"(link)成一个 .exe 可执行程序。
//==============================================================================================

//------------------------------------------------------------------------------------------------
//【包含保护 / include guard】下面三行是几乎所有头文件的标准开场白:
//  #ifndef LOCATIONS_H —— #ifndef 读作 if not defined(如果还没定义过)。
//                        这是一条"预处理指令":正式编译开始前,预处理器先检查
//                        LOCATIONS_H 这个名字是否已定义过。没定义 → 继续往下;
//                        已定义 → 直接跳到 #endif,整段内容不参与编译。
//  #define  LOCATIONS_H —— 紧随其后,立刻定义 LOCATIONS_H,作为"本文件已处理过"的标记。
//  #endif               —— 结束 #ifndef 开启的条件区域。
//  【为什么需要?】#include 的本质是"把指定文件的内容原样复制粘贴进来"。
//  如果本文件沿两条包含链被复制两遍(例如 A.h 和 B.h 都包含本文件,而某个 .cpp
//  又同时包含 A.h 与 B.h),同样的定义会出现两次,编译器就会报"重复定义"错误。
//  有了这三行,第二次复制会被自动跳过。宏的名字本身无所谓,全工程唯一即可。
//------------------------------------------------------------------------------------------------
#ifndef LOCATIONS_H
#define LOCATIONS_H


//--------------------------------------------------------------------------------
//【枚举 enum —— 一种"只能取固定几个值"的整数类型】
//  语法:enum 类型名 { 选项1, 选项2, ... };
//    enum          :C++ 关键字,表示"定义一个枚举(enumeration)类型"。
//    location_type :给这个新类型起的名字。以后可以像用 int 那样,用
//                    location_type 声明变量(见 Miner.h 里的 m_Location)。
//    花括号里的内容:叫"枚举项"。不显式赋值时编译器自动编号:
//                    shack=0、goldmine=1、bank=2、saloon=3(从 0 开始依次加 1)。
//  【好处】枚举项 = "有名字的整数":既保留整数的高效,又让代码读起来像英文。
//--------------------------------------------------------------------------------
enum location_type
{
  // shack(小屋/窝棚):矿工 Bob 的家。疲劳超过 TirednessThreshold(见 Miner.h)
  // 时回家睡觉(状态 GoHomeAndSleepTilRested),每睡一步疲劳值 -1。
  shack,
  // goldmine(金矿):矿工的"上班地点"(状态 EnterMineAndDigForNugget),
  // 每挖一步金块 +1、疲劳 +1。
  goldmine,
  // bank(银行):把口袋里的金块兑换成存款的地方(状态 VisitBankAndDepositGold)。
  // 存款达到 ComfortLevel(5)矿工就心满意足回家。
  bank,
  // saloon(酒吧/酒馆):口渴值达到 ThirstLevel(见 Miner.h)时来买威士忌
  // (状态 QuenchThirst),一杯 2 块钱,喝完口渴值清零。
  saloon
};








#endif