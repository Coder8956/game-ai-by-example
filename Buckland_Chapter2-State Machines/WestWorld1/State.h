//==============================================================================================
//【文件说明】State.h —— "状态"的抽象接口(整个状态机设计的总规范)
//
//【这个文件是干什么的?】
//  定义 class State —— 一个"纯抽象基类"(也可以叫"接口"):它自己什么都不干,
//  只负责规定"凡是想当'矿工的状态',就必须会做三件事":
//      Enter(...)   —— 进入本状态时执行一次(通常负责赶路 + 念开场白);
//      Execute(...) —— 处于本状态期间,矿工每 Update() 一次就执行一次
//                      (干活 + 决定要不要切换到别的状态);
//      Exit(...)    —— 离开本状态时执行一次(通常念告别词)。
//  矿工的 4 个具体状态类(在 MinerOwnedStates.h/.cpp 里:挖矿/存钱/睡觉/喝酒)
//  各自继承 State 并把这三个函数全部实现。
//
//【状态机思想】矿工类(Miner.h)只用一个指针 m_pCurrentState 保存"当前状态",
//  矿工自己永远不决定"现在该干什么",而是把决策权全权交给这个指针指向的状态
//  对象;"切换状态"就是"把指针改指向另一个状态对象"。行为的逻辑不再堆在
//  矿工的一长串 if-else 里,而是分散到一个个小状态类中——这就是设计模式
//  "状态模式"(State Pattern)的核心,游戏 AI 里的"有限状态机"FSM 即由此而来。
//
//【与相关文件的关系】
//  1. MinerOwnedStates.h —— 用 #include 包含本文件,4 个具体状态类都继承 State;
//  2. Miner.h            —— 前置声明了 class State; 并声明成员
//                           State* m_pCurrentState(当前状态指针);
//  3. Miner.cpp          —— ChangeState() 里调用状态的 Enter/Exit,
//                           Update() 里调用状态的 Execute;
//  4. BaseGameEntity.h   —— 无直接关系;Miner 同时继承它(管编号),
//                           又持有 State 指针(管行为)。
//
//【C++ 语法要点】
//  class Miner;        = 前置声明:只报名字不给内容,因为下面参数只用 Miner* 指针;
//  virtual ~State(){}  = 虚析构函数:保证将来用"基类指针"删除子类对象时,
//                       能正确调用子类的析构函数(基类必备写法,见函数旁注释);
//  virtual ... = 0;    = 纯虚函数:本类不给实现,强迫每个子类必须自己实现;
//                       含纯虚函数的类 = 抽象类,不能直接创建对象,只能当父类用。
//==============================================================================================

// 包含保护(原理详解见 Locations.h):防止本文件被重复包含。
