// 前置声明(forward declaration):只告诉编译器"Miner 是一个类",
// 不给出类的具体内容。为什么可以这样?因为下面三个函数的参数
// 只用到"Miner 指针"(Miner*)——指针只存一个内存地址,大小固定,
// 编译器不需要知道 Miner 类里有什么成员。Miner 的完整定义在 Miner.h,
// 由具体实现状态的 MinerOwnedStates.cpp 去包含它。
class Miner;

//--------------------------------------------------------------------------------
//【State —— 状态接口类】
//   class State : 定义一个名叫 State 的类;花括号里的内容是类体,
//                 类定义结尾的分号";"是 C++ 规定,不能省略。
//   注意:本类没有数据成员,只有三个"纯虚函数"——所以它只当"合同/模板"用,
//   不保存任何状态数据(矿工的数据都在 Miner 对象里)。
//--------------------------------------------------------------------------------
class State
{
public:

  // 【虚析构函数】"~类名"就是析构函数(destructor):对象寿命结束、被销毁时
  // 自动执行的收尾函数(与构造函数正好相反)。花括号{}为空 = 目前没有收尾工作。
  // 前面的 virtual 关键字很重要:将来若子类添加了需要清理的资源,并出现
  // "用 State 指针指向子类对象再 delete"的写法,只有虚析构才能保证调用到
  // 子类自己的析构函数,否则会漏清理(内存泄漏)。所以"基类的析构函数一定
  // 写成 virtual"是 C++ 黄金守则。
  virtual ~State(){}

  //this will execute when the state is entered
  //(原文注释:状态被"进入"时执行的函数)

  // 【进入状态时执行一次】
  //   virtual —— "虚函数":允许子类提供自己的版本,运行时按对象实际类型调用
  //              (这叫"多态")。子类实现函数时也习惯再写一遍 virtual。
  //   void    —— 返回类型为"空":本函数不返回任何东西。
  //   (Miner*)—— 参数:一个"指向矿工的指针"。只写类型不写参数名——声明里
  //              可以这样省略形参名(参数名由实现处的 MinerOwnedStates.cpp
  //              自己取,那里取名叫 pMiner)。
  //   = 0     —— "纯虚"标记:本类不提供函数体,强制子类必须实现它;
  //              只要有一个纯虚函数,本类就是"抽象类",不能创建 State 对象,
  //              只能被继承。这相当于在合同里写死:想当状态,就必须会"进入"。
  virtual void Enter(Miner*)=0;

  //this is the state's normal update function
  //(原文注释:这是状态平常的更新函数)

  // 【状态的"日常"】矿工每次 Update() 都会把控制权交给当前状态的这个函数,
  // 它负责干活并决定是否切换到别的状态(调用 pMiner->ChangeState(...))。
  virtual void Execute(Miner*)=0;

  //this will execute when the state is exited. (My word, isn't
  //life full of surprises... ;o))
  //(原文注释:状态被"退出"时执行的函数。括号里作者开了句玩笑:
  //  "天哪,人生真是处处有惊喜…;o)")

  // 【离开状态时执行一次】由 Miner::ChangeState() 在切换前自动调用。
  virtual void Exit(Miner*)=0;

};

#endif