//==============================================================================================
//【程序总览】WestWorld1 —— 《Programming Game AI by Example》
//  (中文译名《游戏人工智能编程案例精粹》)第 2 章"状态机"的第一个示例程序。
//
// 这是一个运行在黑色"控制台窗口"里的超简易游戏,演示游戏 AI 最经典的设计模式:
// ★ 有限状态机(Finite State Machine,简称 FSM)★
//
//【游戏剧情】西部世界里住着矿工 Bob。他的"人生"被拆成一个个状态:
//   挖金矿 → 口袋装满(3 块)→ 去银行存钱 → 存款够 5 块就回家睡觉
//   → 睡醒了再去挖矿 → …… 挖矿挖到口渴(5 点)就先去酒吧买杯威士忌。
// 程序每 0.8 秒打印一行 Bob 的台词/行为,总共演 20 幕,像看小剧场一样。
//
//【整个工程的文件地图及相互关系】(带 ▶ 的箭头表示"包含/使用"方向)
//   main.cpp(本文件:程序唯一入口——创建矿工,再循环驱动他生活 20 步)
//      │
//      ├────▶ Locations.h      —— 地点枚举:小屋/金矿/银行/酒吧。
//      │                        (main 没直接用到,包含它只是习惯写法)
//      ├────▶ Miner.h ─ Miner.cpp 是它的实现
//      │           ↑ Miner.h 又包含 Locations.h,并继承 BaseGameEntity.h
//      │           └ 矿工类:矿工的"身体数据"(位置/金块/存款/口渴/疲劳)
//      │             + 行为(Update、ChangeState),并持有"当前状态"指针。
//      ├────▶ BaseGameEntity.h ─ BaseGameEntity.cpp 是它的实现
//      │           所有角色的"祖宗类"(基类):发唯一编号 ID,
//      │           并强制所有子类必须实现 Update()。
//      ├────▶ EntityNames.h    —— 角色编号枚举(0=Bob,1=Elsa)
//      │                        + 把编号翻译成名字的 GetNameOfEntity()。
//      ├────▶ misc/ConsoleUtils.h —— 控制台小工具(文字颜色、按任意键继续)。
//      │           注意:它不在本文件夹,而在上上级的 Common\misc\ 公共目录,
//      │           靠工程"附加包含目录 ..\..\Common"的设置才能被找到。
//      │
//      │      State.h(状态接口:规定每个状态必须有 Enter/Execute/Exit)
//      │           ▲ 被 MinerOwnedStates.h 继承实现
//      │      MinerOwnedStates.h ─ MinerOwnedStates.cpp 是它的实现
//      │           4 个具体状态类:挖矿/存钱/睡觉/喝酒(都是单例),
//      │           每个状态里决定"何时切换到哪个状态"。
//      │           (main.cpp 没直接包含它;是 Miner.h/.cpp 在使用)
//
//【一次完整循环的调用流程】(建议按此顺序阅读各文件)
//   ① main() 创建 Miner 对象(出生在小屋,初始状态=回家睡觉);
//   ② main 循环调用 miner.Update();
//   ③ Miner::Update() 先让口渴值 +1,再调用"当前状态"的 Execute();
//   ④ 状态类(如挖矿)在 Execute 里干活,并在合适时机调用
//      miner.ChangeState(下一个状态::Instance());
//   ⑤ ChangeState 里:旧状态 Exit → 换指针 → 新状态 Enter;
//   ⑥ 回到 ②,状态机永不停歇——矿工就这样"活"了起来。
//==============================================================================================

//--------------------------------------------------------------------------------
// #include 是"预处理指令":编译前的预处理阶段,把引号/尖括号里那个文件的
// 全部内容原样复制粘贴到这一行所在的位置。
// 双引号 "xxx.h":先到本工程目录及工程设置的"附加包含目录"里找;
// 尖括号 <xxx.h>:只到编译器的系统/标准库目录里找(标准库都用尖括号)。
//--------------------------------------------------------------------------------

// 本工程自己的头文件:定义了 location_type 地点枚举(shack/goldmine/bank/saloon)。
// main 本身没直接用到地点,包含它是原作者的习惯写法(真正用地点的是 Miner.h)。
#include "Locations.h"
// 矿工类的"说明书":不包含它,编译器根本不认识下面 main 里写的 Miner 是什么。
#include "Miner.h"
// Common\misc\ 目录里的控制台工具:提供本文件用到的 PressAnyKeyToContinue()。
// "misc/xxx.h" 表示"附加包含目录下的 misc 子文件夹里的 xxx.h"。
#include "misc/ConsoleUtils.h"
// 角色编号枚举:下面创建矿工时用的编号 ent_Miner_Bob(值为 0)定义在这里。
#include "EntityNames.h"


//--------------------------------------------------------------------------------
// int main() —— 程序的入口函数。
//   int   :返回类型——本函数结束后返回一个整数给操作系统;
//   main  :名字是 C++ 规定死的,操作系统启动程序后就从这里开始执行;
//   ()    :空的参数表,表示不接收命令行参数
//           (也可以写 int main(int argc, char* argv[]) 来接收,本程序不需要);
//   { }   :函数体,花括号内是逐行执行的全部代码。
//--------------------------------------------------------------------------------
int main()
{
  //create a miner
  //(原文注释:创建一个矿工)

  // 【创建(实例化)一个矿工对象】
  //   Miner         —— 类名(相当于"图纸");
  //   miner         —— 对象名(按图纸造出来的"实物",给这个变量取名 miner);
  //   ent_Miner_Bob —— 传给构造函数的参数:矿工编号(来自 EntityNames.h,值为 0)。
  // 创建对象时 C++ 自动调用 Miner 的"构造函数"(实现在 Miner.cpp),它会把矿工
  // 初始化为:身在小屋、金块 0、存款 0、口渴 0、疲劳 0、当前状态=回家睡觉状态。
  Miner miner(ent_Miner_Bob);

  //simply run the miner through a few Update calls
  //(原文注释:简单地对矿工做几次 Update 调用)

  // 【for 循环:让花括号里的代码重复执行 20 次】
  //   int i=0  :循环开始前执行一次——定义计数器 i,赋初值 0;
  //   i<20     :每轮开始前检查,条件为"真"才继续循环;
  //   ++i      :每轮结束后执行——让 i 加 1("++"读作"自增")。
  //   三段用分号隔开。i 从 0 涨到 19,共执行 20 轮,模拟矿工"生活"的 20 个时间片。
  for (int i=0; i<20; ++i)
  { 
    // "点号"是成员访问运算符:对象名.函数名() 表示调用这个对象的成员函数。
    // Update() 是矿工的"心跳"(实现在 Miner.cpp):
    // 每调用一次,口渴值 +1,并把行动决策交给"当前状态"的 Execute()——
    // 当前状态是谁,矿工这步就干什么活,可能会触发状态切换。
    miner.Update();

    // Sleep:Windows 系统函数(在 windows.h 中声明,前面的 ConsoleUtils.h
    // 间接包含了它)。作用:暂停当前程序 800 毫秒(0.8 秒)。
    // 加上这句,输出就像逐幕播放的小剧场;没有它,20 行会瞬间刷完。
    Sleep(800);
  }

  //wait for a keypress before exiting
  //(原文注释:退出前等待按键)

  // 来自 ConsoleUtils.h 的工具函数:打印 "Press any key to continue",
  // 然后原地等待,直到用户按下键盘上任意一个键。
  // 作用:让命令行窗口在程序结束前停住,不会一闪而过。
  PressAnyKeyToContinue();

  // 把整数 0 返回给操作系统。约定俗成:0 表示"程序正常结束",非 0 表示出错。
  return 0;
}