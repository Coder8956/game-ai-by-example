//==============================================================================================
//【文件说明】EntityNames.h —— 角色的"身份证编号表"和"编号→名字"翻译器
//
//【这个文件是干什么的?】
//  游戏里有 2 个角色:矿工 Bob(编号 0)和他的妻子 Elsa(编号 1)。
//  程序内部不用名字交流,只用整数编号(如 ent_Miner_Bob = 0);
//  但打印到屏幕上时又想让玩家看到"人名"而不是干巴巴的数字。
//  本文件就干两件事:① 用枚举给两个角色定编号;② 提供 GetNameOfEntity() 函数,
//  把编号翻译回名字字符串,方便 cout 打印。
//
//【谁在使用这个文件?】
//  几乎所有要"打印角色名字"的文件都会包含它,包括:
//  1. main.cpp                     —— 创建矿工时用 ent_Miner_Bob 当构造参数;
//  2. MinerOwnedStates.cpp / MinersWifeOwnedStates.cpp —— 打印台词时调用
//                                      GetNameOfEntity(角色->ID()) 得到名字;
//  3. MessageDispatcher.cpp        —— 打印消息派发日志时显示收发双方的名字;
//  4. Miner.cpp / MinersWife.cpp   —— 被它们包含的头文件间接带进来。
//
//【注意】本文件同时被"发送方"和"接收方"使用,是消息系统里
//        所有角色共同的"身份字典"。新增角色时,只需在这里加一个枚举项。
//==============================================================================================

//------------------------------------------------------------------------------------------------
// 包含保护(原理详解见 Locations.h):防止本文件被重复包含。
//------------------------------------------------------------------------------------------------
#ifndef NAMES_H
#define NAMES_H

// #include <string>:包含 C++ 标准库的 string(字符串)类型定义。
// 尖括号 < > 表示"只到编译器系统目录里找",这是标准库的找法。
// 下面 GetNameOfEntity 的返回类型 std::string 就来自这里。
#include <string>

//--------------------------------------------------------------------------------
//【无名枚举(anonymous enum)】enum 后面没有类型名,直接写花括号。
// 效果:枚举项直接成为全局可用的整数常量(不要求用"类型名::"限定)。
//   ent_Miner_Bob —— 矿工 Bob 的编号。自动从 0 开始编号,所以它的值 = 0;
//   ent_Elsa      —— 妻子的编号,自动 +1,值 = 1。
// 为什么要用枚举而不是直接写数字 0/1?
//  因为代码里写 ent_Miner_Bob 比写 0 好懂得多,而且编译器能帮你检查拼写。
//--------------------------------------------------------------------------------
enum 
{
  ent_Miner_Bob,

  ent_Elsa
};

//--------------------------------------------------------------------------------
//【内联函数 inline】GetNameOfEntity(int n):
//  作用:输入一个角色编号 n,返回对应的名字字符串(std::string)。
//  语法逐词拆解:
//    inline        :关键字"内联"。意思是在每个调用处直接把函数体"复制粘贴"
//                    进去,省去一次函数调用开销。对这种极小的函数很合适;
//    std::string   :返回类型,C++ 标准库的字符串类型(std:: 是命名空间前缀);
//    GetNameOfEntity :函数名,读作"Get Name Of Entity"(取得实体的名字);
//    (int n)       :参数表。接收一个 int 整数 n,表示要查询的角色编号;
//    { ... }       :函数体,花括号内是具体逻辑。
//--------------------------------------------------------------------------------
inline std::string GetNameOfEntity(int n)
{
  // switch(n):多分支选择语句。拿 n 的值去和下面每个 case 后面写的值比较,
  // 等于哪个 case,就执行哪个 case 下面的语句,直到遇到 break 或函数返回。
  switch(n)
  {
  case ent_Miner_Bob:

    // return:立刻结束本函数,并把右边的值作为"返回值"交还给调用者。
    // 双引号 "..." 是字符串字面量(直接写死的文本)。
    // 后面的 (矿工鲍勃) 是中文译名,方便中文读者一眼看懂(原有改动,保留)。
    return "Miner Bob(矿工鲍勃)";

  case ent_Elsa:
    
    return "Elsa(艾尔莎)"; 

  default:

    // default:如果 n 不等于上面任何一个 case(即编号非法),就执行这里。
    return "UNKNOWN!(未知!)";
  }
}

// 包含保护结束:与文件开头的 #ifndef NAMES_H 配对。
#endif