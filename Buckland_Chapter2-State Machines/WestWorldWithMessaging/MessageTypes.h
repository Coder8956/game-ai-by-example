//==============================================================================================
//【文件说明】MessageTypes.h —— 消息类型的"编号表"和"编号→文字"翻译器
//
//【这个文件是干什么的?】
//  角色之间靠"消息"(message)交流,例如矿工回家时给妻子发一条"我回来了",
//  妻子炖好菜后给矿工发一条"炖菜好了"。程序内部这些消息只是整数编号,
//  打印日志时又想让玩家看懂是什么消息——本文件负责这两件事:
//    ① 用枚举定义本工程用到的全部消息类型;
//    ② 提供 MsgToStr() 函数,把消息编号翻译成可读的字符串。
//
//【本工程共有 2 种消息】(消息的收发流程见 MessageDispatcher.cpp 的注释)
//  1. Msg_HiHoneyImHome —— "亲爱的,我回来了":矿工回到家(进入睡觉状态时)
//                           立即发给妻子 Elsa,妻子收到后改去炖菜;
//  2. Msg_StewReady     —— "炖菜好了":妻子把菜放进烤箱后,给自己发一条
//                           "延迟 1.5 秒"的消息;到点后她再把"炖菜好了"发给
//                           矿工,矿工就从睡觉状态切到"吃炖菜"状态。
//
//【与相关文件的关系】
//  1. MinerOwnedStates.cpp     —— 矿工收到/发送消息时,switch 里比较的
//                                  Msg_StewReady、Msg_HiHoneyImHome 来自本文件;
//  2. MinersWifeOwnedStates.cpp—— 妻子发消息用 Msg_StewReady 等;
//  3. MessageDispatcher.cpp    —— 打印消息日志时调用 MsgToStr() 翻译消息名;
//  4. Telegram.h(Common 共享) —— 消息的"信封"结构,字段 Msg 里装的就是
//                                  本文件的枚举编号。
//==============================================================================================

//------------------------------------------------------------------------------------------------
// 包含保护(原理详解见 Locations.h):防止本文件被重复包含。
//------------------------------------------------------------------------------------------------
#ifndef MESSAGE_TYPES
#define MESSAGE_TYPES

// std::string 类型来自 C++ 标准库,下面 MsgToStr 的返回类型要用它。
#include <string>

//--------------------------------------------------------------------------------
//【枚举 message_type】定义本工程全部消息类型的编号。
//  注意:这里枚举名是 message_type(和 Locations.h 的 location_type 命名风格一致)。
//  不显式赋值时,编译器自动从 0 开始编号:
//    Msg_HiHoneyImHome = 0
//    Msg_StewReady     = 1
//  枚举名读法:Msg = Message(消息),HiHoneyImHome = 嗨亲爱的我回家了,
//  StewReady = 炖菜好了。
//--------------------------------------------------------------------------------
enum message_type
{
  // 消息①:矿工回家时发给妻子"亲爱的,我回家了"(值 = 0)。
  Msg_HiHoneyImHome,
  // 消息②:妻子通知"炖菜好了"(值 = 1)。注意末尾有逗号,这是 C++ 允许的
  // (最后一个枚举项后面也可以带逗号,方便以后追加新消息)。
  Msg_StewReady,
};


//--------------------------------------------------------------------------------
//【内联函数 inline】MsgToStr(int msg):
//  作用:输入消息编号,返回描述消息的文字(供打印日志使用)。
//  std::string :返回类型,C++ 标准库字符串;
//  (int msg)   :参数,要翻译的消息编号;
//  switch(msg) :拿 msg 与下面每个 case 比较,匹配哪个就 return 哪个字符串。
//--------------------------------------------------------------------------------
inline std::string MsgToStr(int msg)
{
  switch (msg)
  {
  case Msg_HiHoneyImHome:
    
    // return 字符串字面量;括号里是中文译名(原有改动,保留)。
    return "HiHoneyImHome(亲爱的我回家了)"; 

  case Msg_StewReady:
    
    return "StewReady(炖菜好了)";

  default:

    // default:编号不属于上面任何一个 case,说明收到了未知消息。
    return "Not recognized!(无法识别!)";
  }
}

// 包含保护结束:与文件开头的 #ifndef MESSAGE_TYPES 配对。
#endif