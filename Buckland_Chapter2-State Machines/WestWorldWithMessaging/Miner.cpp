//==============================================================================================
//【文件说明】Miner.cpp —— 矿工 Bob 的"行为剧本"(实现文件)
//
//【这个文件是干什么的?】
//  头文件 Miner.h 里声明的矿工方法,在这里给出真正实现:
//    ① HandleMessage —— 收到消息时转交给状态机处理;
//    ② Update        —— 每帧"心跳":口渴 +1,再让状态机跑当前状态;
//    ③ AddToGoldCarried / AddToWealth —— 加金块/加存款(带防负数保护);
//    ④ Thirsty / Fatigued —— 两个"判断阈值"的小函数。
//
//【与相关文件的关系】
//  1. Miner.h             —— 本文件第一行就包含它(类声明都在这里);
//  2. MinerOwnedStates.cpp —— 状态类通过 pMiner->Update() 以外的接口
//                              (AddToGoldCarried 等)驱动矿工干活;
//  3. main.cpp            —— 主循环里每帧调用 Bob->Update()。
//
//【一句话看懂矿工的一天】
//  main 每 0.8 秒调一次 Update → 口渴 +1 → 状态机让"当前状态"执行动作
//  (挖矿/存钱/睡觉/喝酒/吃炖菜) → 状态可能切换 → 循环往复。
//==============================================================================================

// 包含矿工类声明(以及它带进来的父类、地点、状态机等)。
#include "Miner.h"

//--------------------------------------------------------------------------------
//【HandleMessage —— 矿工收消息的入口】
//  bool:返回"消息是否已被处理"(true=处理了,false=没处理)。
//  (const Telegram& msg):消息信封的常量引用。
//  实现:直接把消息转交给状态机 m_pStateMachine 的 HandleMessage。
//  状态机会依次问"当前状态"和"全局状态"能不能处理(见 StateMachine.h)。
//--------------------------------------------------------------------------------
bool Miner::HandleMessage(const Telegram& msg)
{
  return m_pStateMachine->HandleMessage(msg);
}


//--------------------------------------------------------------------------------
//【Update —— 矿工的心跳,每帧由 main 调用一次】
//  步骤:① 把输出文字设为红色(矿工的专属颜色);
//        ② 口渴值 +1(时间在流逝,人会渴);
//        ③ 让状态机更新 → 当前状态执行它的 Execute()。
//  (注意:矿工没有全局状态,所以这里不用像妻子那样额外跑全局状态。)
//--------------------------------------------------------------------------------
void Miner::Update()
{
  // SetTextColor:来自 ConsoleUtils.h 的"改文字颜色"工具。
  // FOREGROUND_RED:红色前景;FOREGROUND_INTENSITY:高亮(更亮更醒目)。
  // | 是按位或:把两个颜色标志"拼"成一个参数传给系统。
  SetTextColor(FOREGROUND_RED| FOREGROUND_INTENSITY);

  // += 1:口渴值自增 1。数值越大越渴,到 ThirstLevel(5)状态类就会去喝酒。
  m_iThirst += 1;
  
  // 让状态机执行当前状态的 Execute()——矿工这一步具体干什么,
  // 完全由"当前状态"决定(这是状态机模式的核心)。
  m_pStateMachine->Update();
}



//--------------------------------------------------------------------------------
//【AddToGoldCarried —— 增加口袋里的金块数】
//  (const int val):要加的数量(挖矿时传 1)。
//  保护逻辑:加完如果变成负数,强制拉回 0——防止数据被弄成负数。
//--------------------------------------------------------------------------------
void Miner::AddToGoldCarried(const int val)
{
  m_iGoldCarried += val;

  // 如果小于 0,重新赋值为 0(防御性编程,避免负数金块这种不合理状态)。
  if (m_iGoldCarried < 0) m_iGoldCarried = 0;
}

//--------------------------------------------------------------------------------
//【AddToWealth —— 增加银行里的存款】
//  语义同 AddToGoldCarried,只是操作对象变成存款 m_iMoneyInBank。
//--------------------------------------------------------------------------------
void Miner::AddToWealth(const int val)
{
  m_iMoneyInBank += val;

  if (m_iMoneyInBank < 0) m_iMoneyInBank = 0;
}

//--------------------------------------------------------------------------------
//【Thirsty —— 判断矿工渴不渴】
//  const:只读函数,不修改任何成员。
//  逻辑:口渴值 >= ThirstLevel(5) 就返回 true(渴了),否则 false。
//  (if 语句后只有一句话时,可以省略花括号,直接写在下一行。)
//--------------------------------------------------------------------------------
bool Miner::Thirsty()const
{
  if (m_iThirst >= ThirstLevel){return true;}

  return false;
}

//--------------------------------------------------------------------------------
//【Fatigued —— 判断矿工累不累】
//  逻辑:疲劳值 > TirednessThreshold(5) 就返回 true(困了),否则 false。
//  注意这里用的是 >(大于),与 Thirsty 的 >=(大于等于)不同——原作者的细节。
//--------------------------------------------------------------------------------
bool Miner::Fatigued()const
{
  if (m_iFatigue > TirednessThreshold)
  {
    return true;
  }

  return false;
}
