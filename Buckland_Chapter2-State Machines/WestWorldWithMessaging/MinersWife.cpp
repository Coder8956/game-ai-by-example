//==============================================================================================
//【文件说明】MinersWife.cpp —— 矿工妻子 Elsa 的"行为剧本"(实现文件)
//
//【这个文件是干什么的?】
//  头文件 MinersWife.h 里声明的两个方法,在这里给出实现:
//    ① HandleMessage —— 收消息时转交给状态机处理;
//    ② Update        —— 每帧"心跳":先跑全局状态,再跑当前状态。
//
//【与相关文件的关系】
//  1. MinersWife.h           —— 本文件第一行就包含它(类声明在这里);
//  2. MinersWifeOwnedStates.cpp —— 状态类通过 wife-> 接口驱动妻子的行为;
//  3. main.cpp               —— 主循环里每帧调用 Elsa->Update()。
//
//【与矿工 Update 的区别(重要!)】
//  矿工 Miner::Update:口渴 +1 → 只让状态机跑"当前状态";
//  妻子 MinersWife::Update:不累加任何数值 → 状态机"先全局后当前"。
//  差别源于 StateMachine::Update 的实现:若设置了全局状态 m_pGlobalState,
//  就先执行它(妻子的随机去厕所念头),再执行当前状态(做家务等)。
//  矿工没设全局状态,所以只有当前状态在跑。
//==============================================================================================

// 包含妻子类声明(以及它带进来的状态机、地点等)。
#include "MinersWife.h"

//--------------------------------------------------------------------------------
//【HandleMessage —— 妻子收消息的入口】
//  与矿工一样,把消息转交给状态机。状态机先问"当前状态"能否处理,
//  不能则问"全局状态"能否处理(妻子的炖菜消息主要由当前状态 CookStew
//  和全局状态 WifesGlobalState 处理)。
//--------------------------------------------------------------------------------
bool MinersWife::HandleMessage(const Telegram& msg)
{
  return m_pStateMachine->HandleMessage(msg);
}


//--------------------------------------------------------------------------------
//【Update —— 妻子的心跳,每帧由 main 调用一次】
//  步骤:① 把输出文字设为绿色(妻子的专属颜色,与矿工的红色区分);
//        ② 让状态机更新——状态机内部会先执行全局状态 WifesGlobalState
//           (可能随机切去上厕所),再执行当前状态(做家务等)。
//  注意:妻子没有像矿工那样的口渴/疲劳数值,Update 里不需要累加。
//--------------------------------------------------------------------------------
void MinersWife::Update()
{
  //set text color to green
  //(原文注释:把文字颜色设为绿色)

  // 绿色前景 + 高亮(矿工是红色,妻子是绿色,一眼分清谁在说话)。
  SetTextColor(FOREGROUND_GREEN | FOREGROUND_INTENSITY);
 
  // 状态机更新:先跑全局状态,再跑当前状态(见 StateMachine.h 的 Update)。
  m_pStateMachine->Update();
}