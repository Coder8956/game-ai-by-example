//
//【这个文件是干什么的?】
//  1. Miner::Update()          —— 矿工的"心跳":每被调用一次就活一步
//                                (设置台词颜色、口渴 +1、把决策权交给状态机);
//  2. 一组小工具的实现:加金块(AddToGoldCarried)、加存款(AddToWealth)、
//     判断口渴(Thirsty)、判断困倦(Fatigued)。
//  【对比 WestWorld1】矿工的构造函数与"切换状态"ChangeState 不在这里了:
//  构造函数已改写进 Miner.h(类内定义);ChangeState 的活整个交给了
//  StateMachine.h 里的通用状态机(切换入口:角色->GetFSM()->ChangeState(...))。
//
//【与相关文件的关系】
//  Miner.h            —— 本文件实现它声明的类,第一件事就是包含它;
//  misc/ConsoleUtils.h —— SetTextColor(设置控制台文字颜色)来自这个公共
//                        目录(..\..\Common\misc\,靠工程"附加包含目录
//                        ..\..\Common"的设置才能被找到);
//  StateMachine.h     —— (经 Miner.h 间接包含)Update() 把决策权转交给
//                        m_pStateMachine->Update(),由它驱动当前状态;
//  MinerOwnedStates.cpp —— 状态的 Execute() 最终在那里干活、决定切不切换;
//  main.cpp           —— main() 创建矿工后,循环调用这里的 Update(),
//                        驱动整个状态机。
//
//【C++ 语法:"类名::函数名"中的双冒号 "::"】
//  叫"作用域解析运算符"(scope resolution operator)。
//  "Miner::Update" 读作"Miner 类里的那个 Update"——写在类外面的函数实现,
//  必须用"类名::函数名"说明"这是谁家的函数",否则编译器以为你在写一个
//  不相干的散函数。
//==============================================================================================

// 包含自己的头文件:实现前必须先见到"矿工类长什么样"(有哪些成员和声明)。
#include "Miner.h"
// Common\misc\ 目录里的控制台工具:提供下面用到的 SetTextColor()。
#include "misc/ConsoleUtils.h"


//-----------------------------------------------------------------------------
//【矿工的"心跳":每步更新】——整个状态机的发动机。
// main.cpp 的 for 循环每圈调用一次 Bob.Update()。
// 注意:矿工自己只做三件事——设颜色、口渴值 +1、把行动决策权交给状态机。
// 矿工从不用 if-else 判断"我该干什么"——一切交给状态,这就是状态机精髓。
//-----------------------------------------------------------------------------
void Miner::Update()
{
  // 【设置控制台文字颜色】矿工的台词统一用"亮红色"打印(妻子用绿色,见
  // MinersWife.cpp,两人台词在屏幕上一眼可分)。
  //   SetTextColor      —— ConsoleUtils.h 提供的小工具函数;
  //   FOREGROUND_RED    —— "前景色红"常量(wincon.h 里定义的开关标志,数字 4);
  //   FOREGROUND_INTENSITY —— "高亮加粗"标志(数字 8);
  //   "|"               —— "按位或"运算符:把两个标志的比特合并到一起,
  //                        4|8=12,一个开关字节里同时点亮"红"和"亮"两盏灯。
  //                        (注意:这是单个竖线,与"逻辑或"|| 是两种运算。)
  SetTextColor(FOREGROUND_RED| FOREGROUND_INTENSITY);

  // 每活一步,口渴值 +1(时间流逝,人越来越渴)。
  // "+=" 读作"自身加上":等价于 m_iThirst = m_iThirst + 1。
  m_iThirst += 1;
  
  // 把决策权交给状态机:让它先执行全局状态(矿工没装,自动跳过)、再执行
  // 当前状态的 Execute(this 把矿工自己交出去,详见 StateMachine.h)。
  // 实际调用到哪个状态的 Execute,取决于状态机此刻记录的当前状态是谁
  // ——这就是"多态"(同一句话,不同对象不同行为)。
  m_pStateMachine->Update();
}

//-----------------------------------------------------------------------------
//【加金块】给口袋增加 val 块(挖矿状态传 1;负数表示减少)。
// 调用它的是 MinerOwnedStates.cpp 里的挖矿状态(EnterMineAndDigForNugget)。
//-----------------------------------------------------------------------------
void Miner::AddToGoldCarried(const int val)
{
  // "+=" 读作"自身加上"。
  m_iGoldCarried += val;

  // 保护:金块数不允许为负。if(条件) 后只有一条语句时,花括号可以省略——
  // 条件成立时只执行紧跟的那一句。"<" 读作"小于"。
  if (m_iGoldCarried < 0) m_iGoldCarried = 0;
}

//-----------------------------------------------------------------------------
//【加存款】给银行存款增加 val(存金块时传金块数;买酒时传 -2)。
//-----------------------------------------------------------------------------
void Miner::AddToWealth(const int val)
{
  m_iMoneyInBank += val;

  // 同样的"不为负"保护。
  if (m_iMoneyInBank < 0) m_iMoneyInBank = 0;
}

//-----------------------------------------------------------------------------
//【判断口渴】返回 bool(真/假):口渴值 ≥ ThirstLevel(5,常量在 Miner.h)
// 返回 true(渴了),否则返回 false。括号后的 const 表示本函数不修改任何成员
// (原理详见 BaseGameEntity.h 中 ID() 的注释)。
//-----------------------------------------------------------------------------
bool Miner::Thirsty()const
{
  // if(条件){...}:条件为"真"才执行花括号内的代码。
  // ">=" 读作"大于等于"。够渴了 → 立刻返回"真"结束函数。
  if (m_iThirst >= ThirstLevel){return true;}

  // 走到这里说明没渴 → 返回"假"。
  return false;
}


//-----------------------------------------------------------------------------
//【判断困倦】疲劳值 > TirednessThreshold(5,常量在 Miner.h;注意是
// "严格大于"而非"大于等于")返回 true。与 Thirsty() 的写法风格不同
// (花括号分行),但逻辑同理。
//-----------------------------------------------------------------------------
bool Miner::Fatigued()const
{
  if (m_iFatigue > TirednessThreshold)
  {
    return true;
  }

  return false;
}