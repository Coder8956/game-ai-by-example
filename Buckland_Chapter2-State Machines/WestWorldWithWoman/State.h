//--------------------------------------------------------------------------------
//【模板 template —— 让"状态接口"通用于各种角色】
//  template <class entity_type> 这一行读作:"下面紧跟着的那个东西是模板,
//  entity_type 是它的'类型参数',使用时由你填"。
//    template :C++ 关键字,表示"后面是一个模板(通用图纸)";
//    <...>    :尖括号里列出模板的"类型参数",相当于函数的参数表——
//               只不过函数传"值",模板传"类型";
//    class entity_type :类型参数的名字,叫什么都行(约定俗成常叫 entity_type,
//               意为"实体类型")。它此刻只是一个占位符,并不代表任何具体类型。
//  【怎么用?】写 State<Miner> 时,编译器把全文的 entity_type 替换成 Miner,
//  现场造出一份"矿工版 State";写 State<MinersWife> 又造出一份"妻子版 State"。
//  两份代码互不干扰(就像同一张图纸造出的两台机器)。
//  【为什么 WestWorld1 不用模板?】那个示例里只有矿工一个角色,接口参数直接
//  写死成 Miner*;本工程加入了妻子 Elsa,若不做成模板,就得为每种角色
//  复制一份几乎相同的 State 接口——模板让一份代码服务所有角色。
//--------------------------------------------------------------------------------
template <class entity_type>
class State
{
// public:(公有区)从这里到类体结束的成员,外界都能访问。
public:

  // 【虚析构函数】"~类名"就是析构函数(destructor):对象寿命结束、被销毁时
  // 自动执行的收尾函数(与构造函数正好相反)。花括号{}为空 = 目前没有收尾工作。
  // 前面的 virtual 关键字很重要:将来若子类添加了需要清理的资源,并出现
  // "用 State 指针指向子类对象再 delete"的写法,只有虚析构才能保证调用到
  // 子类自己的析构函数,否则会漏清理(内存泄漏)。所以"基类的析构函数一定
  // 写成 virtual"是 C++ 黄金守则。
  virtual ~State(){}

  //this will execute when the state is entered
  //(原文注释:状态被"进入"时执行的函数)

  // 【进入状态时执行一次】
  //   virtual —— "虚函数":允许子类提供自己的版本,运行时按对象实际类型调用
  //              (这叫"多态")。子类实现函数时也习惯再写一遍 virtual。
  //   void    —— 返回类型为"空":本函数不返回任何东西。
  //   (entity_type*)—— 参数:一个"指向'本模板所服务的角色'的指针"。
  //              造出 State<Miner> 后它就是 Miner*,造出 State<MinersWife>
  //              后它就是 MinersWife*。只写类型不写参数名——声明里可以这样
  //              省略形参名(参数名由各子类实现处自己取,矿工的取 pMiner、
  //              妻子的取 wife)。
  //   = 0     —— "纯虚"标记:本类不提供函数体,强制子类必须实现它;
  //              只要有一个纯虚函数,本类就是"抽象类",不能创建 State 对象,
  //              只能被继承。这相当于在合同里写死:想当状态,就必须会"进入"。
  virtual void Enter(entity_type*)=0;

  //this is the states normal update function
  //(原文注释:这是状态平常的更新函数)

  // 【状态的"日常"】角色每次 Update() 都会(经状态机)把控制权交给当前状态
  // 的这个函数,它负责干活并决定是否切换到别的状态。
  virtual void Execute(entity_type*)=0;

  //this will execute when the state is exited. (My word, isn't
  //life full of surprises... ;o))
  //(原文注释:状态被"退出"时执行的函数。括号里作者开了句玩笑:
  //  "天哪,人生真是处处有惊喜…;o)")

  // 【离开状态时执行一次】由状态机(StateMachine.h)的 ChangeState()
  // 在切换前自动调用。
  virtual void Exit(entity_type*)=0;

};

// 配对文件上方 #ifndef STATE_H 的收尾(作用见 Locations.h 的"包含保护"注释)。
#endif