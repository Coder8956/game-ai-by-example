//==============================================================================================
//【文件说明】State.h —— "状态"的抽象接口(整个状态机设计的总规范)
//
//【这个文件是干什么的?】
//  定义 class State —— 一个"纯抽象基类"(也可以叫"接口"):它自己什么都不干,
//  只负责规定"凡是想当'角色的状态',就必须会做三件事":
//      Enter(...)   —— 进入本状态时执行一次(通常负责赶路 + 念开场白);
//      Execute(...) —— 处于本状态期间,角色每 Update() 一次就执行一次
//                      (干活 + 决定要不要切换到别的状态);
//      Exit(...)    —— 离开本状态时执行一次(通常念告别词)。
//  本工程有两套具体状态类,各自继承 State 并把这三个函数全部实现:
//      矿工的 4 个状态(在 MinerOwnedStates.h/.cpp:挖矿/存钱/睡觉/喝酒);
//      妻子的 3 个状态(在 MinersWifeOwnedStates.h/.cpp:全局状态/做家务/上厕所)。
//
//【状态机思想】角色类(Miner / MinersWife)自己永远不决定"现在该干什么",
//  而是把决策权全权交给"状态机"StateMachine.h 里保存的状态对象;
//  "切换状态"就是"把状态机里的指针改指向另一个状态对象"。
//  行为的逻辑不再堆在角色类的一长串 if-else 里,而是分散到一个个小状态
//  类中——这就是设计模式"状态模式"(State Pattern)的核心,游戏 AI 里的
//  "有限状态机"FSM 即由此而来。
//
//【与相关文件的关系】
//  1. MinerOwnedStates.h    —— 用 #include 包含本文件,4 个矿工状态类都写成
//     "class xxx : public State<Miner>"(继承"矿工版"State);
//  2. MinersWifeOwnedStates.h —— 同理,3 个妻子状态类都写成
//     "class xxx : public State<MinersWife>"(继承"妻子版"State);
//  3. StateMachine.h        —— 状态机类同样用模板造出"某角色版状态机",
//     内部保存 State<entity_type>* 状态指针(当前/上一个/全局三种);
//  4. Miner.h / MinersWife.h —— 各自持有一个 StateMachine<自己> 的指针,
//     经它间接使用本接口。本工程与 WestWorld1 不同:State 不再是"矿工专用"
//     的接口,所以本文件里看不到 class Miner 之类的具体角色名。
//
//【C++ 语法要点】
//  template <class entity_type> = 模板:把"状态属于哪种角色"留作参数,
//       同一份接口即可为矿工、妻子(乃至书中后续任何角色)各造一版;
//  virtual ~State(){}  = 虚析构函数:保证将来用"基类指针"删除子类对象时,
//       能正确调用子类的析构函数(基类必备写法,见函数旁注释);
//  virtual ... = 0;    = 纯虚函数:本类不给实现,强迫每个子类必须自己实现;
//       含纯虚函数的类 = 抽象类,不能直接创建对象,只能当父类用。
//==============================================================================================

