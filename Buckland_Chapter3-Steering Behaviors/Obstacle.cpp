//==============================================================================================
//【文件说明】Obstacle.cpp —— 障碍物的"存盘/读盘"实现
//
//【这个文件是干什么的?】
//  实现 Obstacle.h 里声明的两个函数:
//    Write() —— 把障碍物(类型、位置、半径)写成一行文本,方便存进文件;
//    Read()  —— 从文件里读出一行文本,还原出障碍物的位置和半径。
//  本工程默认不启用存盘功能(相关调用被注释掉了),这两个函数主要是
//  "接口完整"的演示:让 Obstacle 继承的"可读写"能力有具体实现。
//
//【与相关文件的关系】
//  Obstacle.h —— 本文件实现它的 Write/Read 声明;
//  <fstream>  —— C++ 标准库文件流头文件:std::ostream(输出流)和
//                std::ifstream(输入流)定义在这里;
//  BaseGameEntity.h —— (经 Obstacle.h 间接包含)EntityType()/Pos()/BRadius()
//                等数据读取函数都继承自它。
//
//【C++ 小课堂:流(stream)与 <<、>>】
//  C++ 把"文件/屏幕"抽象成"流"。写文件用 <<(流向输出),读文件用 >>
//  (从流提取)。std::endl 是"换行并刷新"。
//==============================================================================================
#include "Obstacle.h"
// 包含标准库"文件流"头文件:下面代码用的 std::ostream / std::ifstream
//  (带 std:: 前缀的标准输出/输入文件流)定义在这里。
#include <fstream>


//--------------------------------------------------------------------------------
//【Write:把障碍物数据写入输出流 os】(os = output stream 输出流)
//   返回值 void   —— 不返回东西;
//   Obstacle::Write —— 实现 Obstacle 类里声明的 Write;
//   参数 std::ostream& os —— 输出流的引用(& = 别名,直接操作调用者传入的流,
//                            不拷贝)。const 结尾:本函数不改动任何成员。
//--------------------------------------------------------------------------------
void Obstacle::Write(std::ostream& os)const
{
// 先写一个换行符:每个障碍物占一行,方便以后一行行读回。
// std::endl —— 输出一个换行,并"冲刷"缓冲区。
  os << std::endl;
// 把实体类型(整数)写进流,再接一个逗号。
// <<  —— 流插入运算符:把右边的东西"塞进"左边流里(读作"流向");
// "," —— 用逗号把各数据分开,文件里这一行就长这样:
//        类型,位置,半径。
  os << EntityType() << ",";
// 写入位置向量。Vector2D 重载了 <<,所以整个向量直接写进去即可。
  os << Pos() << ",";
// 写入包围半径(不换行,因为第 7 行已写过换行符——这行是该行的结尾)。
  os << BRadius();
}

//--------------------------------------------------------------------------------
//【Read:从输入流读一个障碍物】(in = input stream 输入流)
//  和 Write 完全相反:用 >>(流提取运算符)从流里依次取出 x、y、r 三个数。
//--------------------------------------------------------------------------------
void Obstacle::Read(std::ifstream& in)
{
// 定义三个局部 double(双精度小数)变量:分别装圆心横坐标 x、纵坐标 y、半径 r。
// (double 是"双精度浮点数",能表示小数。)
  double x, y, r;

// 从输入流连续读三个数:依次填进 x、y、r。
// >> —— 流提取运算符:从流里"取出"一个数装进右边变量。文件里对应 Write
// 写出的那行(位置向量的 x、y 会被 Vector2D 的 >> 重载拆开读)。
  in >> x >> y >> r;

// 把读到的 (x,y) 拼成 Vector2D 位置向量,调用父类的 SetPos() 设为当前位置。
// SetPos 是 BaseGameEntity 提供的"设位置"函数(见 BaseGameEntity.h)。
  SetPos(Vector2D(x,y));
  
// 调用父类 SetBRadius() 设置包围半径。注意上一行末尾有空行,是原样保留的。
  SetBRadius(r);
}