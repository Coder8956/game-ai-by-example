//==============================================================================================
//【文件说明】ParamLoader.cpp —— ParamLoader 类"唯一实例"的实现
//
//【这个文件是干什么的?】
//  整个工程只有这一个函数:Instance()。它负责创建(且只创建一次)ParamLoader
//  对象,并返回它的指针。ParamLoader 的构造函数在 ParamLoader.h 里已经写好了
//  (读 params.ini 的逻辑),Instance() 只需要保证"全工程只有一个实例"即可。
//
//【与相关文件的关系】
//  ParamLoader.h —— 本文件实现它声明的 Instance()。构造函数(读 ini 的代码)
//                    在头文件里;唯一实例的"制造机"在这里。
//  使用方        —— 任何写 Prm.xxx 的代码(SteeringBehaviors.h/.cpp、
//                    Vehicle.cpp、GameWorld.cpp),最终都会调到本函数。
//
//【C++ 小课堂:函数内 static 局部变量 = 懒汉式单例】
//  下面的 static ParamLoader instance; 是"函数内的静态局部变量":
//  ① 第一次执行到这一行时才创建对象(所以叫"懒"——不用不建);
//  ② 之后每次再调用,都直接复用同一个对象,绝不再建第二个;
//  ③ 它的生命周期直到程序结束才销毁。
//  这保证了全工程只有一份参数对象——这就是单例(Singleton)模式的核心。
//==============================================================================================
#include "ParamLoader.h"

//--------------------------------------------------------------------------------
//【Instance():获取全局唯一 ParamLoader 对象的入口】
//   返回值 ParamLoader* —— 指向唯一实例的指针(指针 = 存地址的变量);
//   "类名::函数名" 中的 :: 是作用域解析运算符,表示"实现 ParamLoader 类里
//   声明的那个 Instance 函数"。static 说明这是"类级"函数,不依附于任何对象。
//--------------------------------------------------------------------------------
ParamLoader* ParamLoader::Instance()
{
// 声明一个"函数内静态局部变量":类型是 ParamLoader,名字叫 instance。
// 第一次执行到本行时,自动调用 ParamLoader 的构造函数(读取 params.ini);
// 以后每次执行都跳过构造,直接复用同一个对象(原理见文件头部小课堂)。
  static ParamLoader instance;

// 返回该实例的地址。& 是"取地址运算符":instance 是对象本身,加 & 得到
// 指向它的指针。宏 Prm 展开后是 (*ParamLoader::Instance()),靠的就是这个指针。
  return &instance;
}