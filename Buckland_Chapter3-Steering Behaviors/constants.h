//==============================================================================================
//【文件说明】constants.h —— 全工程共用的"窗口尺寸常量"
//
//【这个文件是干什么的?】
//  定义两个全局常量:窗口宽 500 像素、高 500 像素。第三章的演示程序跑在
//  Windows 图形窗口里(main.cpp 用它们指定窗口大小),"常量"表示整个程序
//  运行期间值不许改变——想改窗口尺寸,只改这里一处即可。
//
//【谁在使用这个文件?】(= 谁用 #include 包含了它)
//  main.cpp             —— 创建窗口时把 constWindowWidth / constWindowHeight
//                          传给 CreateWindowEx(见 main.cpp WinMain 函数);
//  SteeringBehaviors.h  —— 也包含了本文件(习惯性包含,实际未直接用到);
//  GameWorld.cpp        —— 同样包含本文件(习惯性包含)。
//  本文件不包含任何头文件、不定义任何类,只"提供常量",属于最底层的
//  "被依赖者"——别的文件依赖它,它不依赖别人。
//
//【C++ 小课堂:全局常量(const)与"魔法数字"】
//   const int —— 声明一个"只读"整数:初始化后任何代码都不能再修改它。
//   把窗口尺寸抽成有名字的常量,好处有二:
//   ① 可读性:代码里写 constWindowWidth 比写 500 更"自解释";
//   ② 易维护:想调整尺寸只改这一行,全工程跟着生效——不会出现改了这里
//      忘了那里、两个数字不一致的"魔法数字"问题。
//==============================================================================================
#ifndef CONSTANTS_H
#define CONSTANTS_H

// ↓↓↓ 原文注释翻译:"改这些值,后果自负!"(peril = 危险、风险)。
// 警告理由:窗口尺寸被 main.cpp 的 CreateWindowEx 直接使用,若改得太离谱,
// 窗口可能超出屏幕范围。
//change these values at your peril!
// 【逐词拆解】
//   const      —— 常量关键字:这个变量赋值后不许再改;
//   int        —— 类型:整数(integer);
//   constWindowWidth —— 变量名:窗口宽度(Window Width)。名字前的 const 是
//                        原作者命名习惯,提醒读者"这是个常量";
//   = 500      —— 赋初值:宽 500 像素;
//   ;          —— 语句结束符(分号,每条 C++ 语句以它结尾)。
const int constWindowWidth  = 500;
// 【逐词拆解】同上:窗口高度(Height)= 500 像素。宽度、高度都是 500,
// 所以程序窗口是一个正方形。
const int constWindowHeight = 500;


#endif