//  因此本 .cpp 没有任何代码,只保留为工程配套的空文件(满足项目文件组织习惯,
//  也方便以后若要新增球门函数时在此实现)。
//
//【谁在使用它?】
//  没有任何代码从 .cpp 调用东西;所有 Goal 功能都在 Goal.h 中。
//  详见 Goal.h 文件头的关系说明。
