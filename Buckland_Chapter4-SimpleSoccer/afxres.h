//==============================================================================================
//【文件说明】afxres.h —— 资源编译用的"最小桩头"(注意:它不是游戏 AI 的 C++ 源码)
//
//【这个文件是干什么的?】
//  它只服务于 Script1.rc(Windows 资源脚本:菜单、图标等),让资源编译器能找到
//  MFC 的 afxres.h 所提供的符号。由于本机没装 MFC 组件,工程里放了这个等价小文件顶替。
//  它对本足球游戏的逻辑(球员、球、状态机)没有任何影响。
//
//【谁在使用这个文件?】只有 Script1.rc 通过 #include "afxres.h" 包含它;
//  没有任何 .cpp/.h 游戏源码包含它。
//
//【C++ 小课堂:预处理指令(以 # 开头的行)】
//  这些 # 行不是 C++ 语句,而是"预处理器"在正式编译前先做的文字替换工作:
//    #ifndef 名字 —— if not defined:若该名字还没定义过,则保留下面这段;
//    #define 名字    —— 立刻把这个名字标记为"已定义"(常作包含保护用);
//    #ifdef 名字 —— if defined:若该名字已被定义,则保留下面这段;
//    #include <文件> —— 把尖括号里的系统头文件内容复制到此处;
//    #endif      —— 结束上面某个 #ifndef/#ifdef 开启的条件区;
//    (-1)       —— 宏替换时的一对括号,保证替换后运算优先级正确(宏只是纯文字替换)。
//==============================================================================================
//------------------------------------------------------------------------------
//  afxres.h  —  最小替代头（工程级修复，非源码改动）
//
//  原工程 Script1.rc 通过 #include "afxres.h" 引入资源编译符号，该头由 MFC
//  (atlmfc\include\afxres.h) 提供。本机 VS 2026 未安装 "适用于最新 v143 生成
//  工具的 C++ MFC" 组件，故于工程目录放置本最小桩头，内容对齐 MFC 版本中
//  资源脚本实际用到的部分：
//    - 引入 Windows SDK 的 winres.h（资源编译器默认包含路径已含 SDK um 目录）
//    - 提供 IDC_STATIC 等 MFC 常用符号
//  不影响任何 C/C++ 源码的编译。
//------------------------------------------------------------------------------
#ifndef __AFXRES_H__
#define __AFXRES_H__
// 上面两行 #ifndef __AFXRES_H__ / #define __AFXRES_H__ 是"包含保护"开头:
// 保证本文件即使被重复包含也只生效一次(原理详见 Goal.h)。

// #ifdef _WIN32:只有在 Windows 平台编译时,_WIN32 才被自动定义,
// 于是才真正引入 <winres.h>;别的平台下这段被整段跳过(跨平台兼容写法)。
#ifdef _WIN32
#include <winres.h>
// winres.h:Windows SDK 提供的资源头文件,定义菜单/对话框等资源用的符号。
#endif

// #ifndef IDC_STATIC:如果还没人定义过 IDC_STATIC 这个符号,才定义它;
// #define IDC_STATIC (-1):把控件ID "静态文本"规定为 -1(约定俗成的魔法值)。
#ifndef IDC_STATIC
#define IDC_STATIC (-1)
#endif

#endif // __AFXRES_H__
