//==============================================================================================
//【文件说明】constants.h —— 本章(足球模拟)的"全局常量一览表"
//
//【这个文件是干什么的?】
//  把全场用到的"写死的数字"集中放在这里:窗口多大、一支球队几名球员。
//  以后想改窗口尺寸,只改这一处,全工程自动生效(而不用满代码里到处找 700、400)。
//
//【谁在使用这个文件?】(= 哪些文件用 #include 包含了它)
//  main.cpp / SoccerPitch.h / SoccerBall.h / ParamLoader.h
//  FieldPlayerStates.h / GoalKeeperStates.h / SupportSpotCalculator.cpp / TeamStates.cpp
//  —— 它们直接或间接用到 WindowWidth、WindowHeight、TeamSize 这几个常量。
//
//【本文件包含了谁?】
//  什么都没包含——它只定义常量,不依赖别的头文件。
//
//【C++ 小课堂:const(常量)与头文件里定义全局常量】
//  const int WindowWidth = 700; 读作:定义一个整数,名叫 WindowWidth,初值 700,
//  且之后程序里任何地方都不许再给它赋值(改了编译报错)。用常量代替裸数字 700,
//  代码读起来见名知意。头文件里写 const 变量,C++ 规定每个包含它的翻译单元各自
//  拥有一份副本,因此不会出现"重复定义"链接错误,可以安全地放在头文件里。
//==============================================================================================
//--------------------------------------------------------------------------------
// 包含保护(include guard):#ifndef/#define/#endif 三件套,防止本头文件被重复包含。
// 完整原理详解见 Goal.h 中的同名注释(本工程第 1 个详述处),此处不再展开。
//--------------------------------------------------------------------------------
#ifndef CONSTANTS_H
#define CONSTANTS_H

// 窗口客户区宽度(单位:像素)。球场按这个宽度铺,见 SoccerPitch 构造函数。
// = 700 后面的分号 ; 是一条语句的结束符,每个声明都要以它收尾。
const int WindowWidth  = 700;
const int WindowHeight = 400;


//defines the size of a team -- do not adjust
//(原文注释:定义一支球队的人数——不要改动它)
// 每队固定 5 名球员(1 名守门员 + 4 名场上球员),全队站位/区域切分都按此数写死。
const int TeamSize = 5;



#endif