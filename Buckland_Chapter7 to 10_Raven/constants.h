//==============================================================================================
//【文件说明】constants.h —— Raven 工程的「全局窗口常量」小仓库
//
//【这个文件是干什么的?】
//  把整个程序要用的几个魔法数字集中放在一起,起好名字。这样做的好处:
//  ① 别处要用窗口大小时写 WindowWidth,而不是裸写 500,一眼就懂;
//  ② 想改窗口尺寸?只改这一处,全工程自动跟着变。
//
//【谁在使用这个文件?】(= 哪些文件 #include 了 constants.h)
//  main.cpp / Raven_Game.cpp / Raven_Map.cpp 等——创建窗口、布置地图时
//  要用到 WindowWidth / WindowHeight / FrameRate 这三个常量。
//
//【本文件包含了谁?】
//  什么都没包含。它自己就是最底层的纯常量定义,不依赖任何头文件。
//
//【C++ 小课堂:const 常量 与 包含保护】
//   const int WindowWidth = 500;
//     const  :关键字,意思是这是个常量,定义之后不许再赋值修改;
//     int    :整数类型;= 500 :定义时直接给出初值。
//   这种在头文件里直接定义 const 全局变量的写法,是 C++ 允许的特殊规则:
//   普通全局变量被多个 .cpp 包含会重复定义报错,但 const 全局变量每个
//   翻译单元各自拥有一份、互不冲突,所以可以放心写在头文件里。
//==============================================================================================
//--------------------------------------------------------------------------------
// 包含保护:#ifndef CONSTANTS_H / #define CONSTANTS_H / #endif。
// 作用:防止本文件被 #include 两次导致重复定义错误。
// (包含保护原理的完整详解见 Buckland_Chapter2-State Machines\WestWorld1\Locations.h)
//--------------------------------------------------------------------------------
#ifndef CONSTANTS_H
#define CONSTANTS_H



//--------------------------------------------------------------------------------
// 下面 3 行是三个全局常量(全程序任何地方都能直接用,不用加类名前缀):
//   WindowWidth  = 游戏窗口客户区宽度,单位像素,这里是 500;
//   WindowHeight = 游戏窗口客户区高度,单位像素,这里是 500(正方形窗口);
//   FrameRate    = 目标帧率,即每秒想刷新多少帧,这里是 60(每秒 60 帧,很顺滑)。
//--------------------------------------------------------------------------------
const int WindowWidth  = 500;
const int WindowHeight = 500;
const int FrameRate    = 60;


#endif