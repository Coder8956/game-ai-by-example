//==============================================================================================
//【文件说明】Goal_Wander.cpp —— "闲逛"目标的实现
//
//【这个文件是干什么的?】
//  Activate 打开游荡转向;Process 每帧检查一次状态(若没激活就先激活);
//  Terminate 关掉游荡。m_pOwner 是父类存的"所属机器人"指针。
//==============================================================================================
#include "Goal_Wander.h"
#include "..\Raven_Bot.h"
#include "..\Raven_SteeringBehaviors.h"





//---------------------------- Initialize -------------------------------------
//-----------------------------------------------------------------------------  
//--------------------------------------------------------------------------------
// Activate:激活。
void Goal_Wander::Activate()
{
// 状态置为 active(进行中)。
  m_iStatus = active;

// 取出机器人的转向行为器,打开"游荡"开关。
  m_pOwner->GetSteering()->WanderOn();
}

//------------------------------ Process --------------------------------------
//-----------------------------------------------------------------------------
//--------------------------------------------------------------------------------
// Process:每帧调用,返回当前状态码。
int Goal_Wander::Process()
{
  //if status is inactive, call Activate()
// 父类提供的便捷函数:没激活就先激活它。
//(原文注释:若状态是 inactive(未激活),先调用 Activate())
  ActivateIfInactive();

// 返回当前状态码。
  return m_iStatus;
}

//---------------------------- Terminate --------------------------------------
//-----------------------------------------------------------------------------
//--------------------------------------------------------------------------------
// Terminate:终止——关掉游荡转向。
void Goal_Wander::Terminate()
{
// 关闭游荡开关。
  m_pOwner->GetSteering()->WanderOff();
}

