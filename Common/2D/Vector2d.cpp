//==============================================================================================
//【文件说明】Vector2d.cpp —— Vector2D 的"读写流"运算符实现
//
//【这个文件是干什么的?】
//  绝大多数 Vector2D 的函数都写在 Vector2D.h 里(inline)。只有 operator<<(打印)
//  和 operator>>(读入)这两个放进了 .cpp:让向量能像普通数字一样 cout << v 或 cin >> v,
//  主要用于调试输出和从数据文件读坐标。
//
//【本文件包含了谁?】
//  Vector2D.h  —— 自己的类声明;
//  <fstream>   —— 文件输入输出流(ifstream 从文件读)。
//==============================================================================================
#include "Vector2D.h"
#include <fstream>

//--------------------------------------------------------------------------------
// operator<< :定义 "输出流 << 向量" 的行为(如 cout << myVec)。
//   std::ostream& :返回输出流引用(便于链式 cout << a << b);
//   os           :被写入的输出流;rhs :要打印的向量。
//   下面 os << " " << rhs.x ... 就是依次写空格、x、空格、y。
//--------------------------------------------------------------------------------
std::ostream& operator<<(std::ostream& os, const Vector2D& rhs)
{
  os << " " << rhs.x << " " << rhs.y;

  return os;
}

  
//--------------------------------------------------------------------------------
// operator>> :定义 "输入流 >> 向量"(如从文件读出 x、y 填进向量)。
//   std::ifstream& :文件输入流;lhs :被写入的向量(注意没有 const,要改它)。
//--------------------------------------------------------------------------------
std::ifstream& operator>>(std::ifstream& is, Vector2D& lhs)
{
  is >> lhs.x >> lhs.y;

  return is;
}

