//==============================================================================================
//【文件说明】NodeTypeEnumerations.h —— 图论模块的"节点编号约定"小公共头
//
//【这个文件是干什么的?】
//  图(Graph)里每个节点都有一个整数编号。本文件只定义了一个常量:
//  invalid_node_index = -1,意思是"这个编号不指向任何节点"——用来当"空"的标志。
//  比如寻路算法找不到路时,就把结果节点设成 -1 表示"无解"。
//
//【谁在使用这个文件?】
//  GraphEdgeTypes.h / GraphNodeTypes.h / SparseGraph.h / GraphAlgorithms.h
//  HandyGraphFunctions.h —— 第 5 章寻路工程(Pathfinder)用到的整套图模块,
//                            凡是需要"无效节点"标志的地方都 #include 它。
//
//【本文件包含了谁?】
//  无。本文件是最底层的常量定义,不依赖任何头文件。
//
//【C++ 小课堂:匿名枚举(anonymous enum)】
//  写法是 enum { ... }; 不写枚举名。它等价于一组 const int 常量,
//  但好处是编译器会把枚举值当整数用,且不占用变量空间——纯文本替换式的常量。
//  包含保护(#ifndef/#define/#endif)的原理详见 Buckland_Chapter4-SimpleSoccer/Goal.h。
//==============================================================================================
#ifndef NODE_TYPE_ENUMS
#define NODE_TYPE_ENUMS
//--------------------------------------------------------------------------------
// 包含保护:若 NODE_TYPE_ENUMS 还没定义过就继续,并立刻定义它做标记(原理见 Goal.h)。
//--------------------------------------------------------------------------------
//-----------------------------------------------------------------------------
//
//  Name:   NodeTypeEnumerations.h
//
//  Author: Mat Buckland (www.ai-junkie.com)
//
//  Desc:   enumerates some dummy node values that can be assigned to graph
//          edges and nodes
//-----------------------------------------------------------------------------
//--------------------------------------------------------------------------------
// 匿名枚举:定义图模块共用的"无效节点编号"常量。
//   invalid_node_index = -1 :整数编号从 0 开始计数,负数不可能是合法节点,
//                             所以拿 -1 当"没有节点"的哨兵值(sentinel)。
//--------------------------------------------------------------------------------
  enum 
  {
    invalid_node_index    = -1
  // 花括号内列出枚举常量;末尾分号不能省。
  };
  

#endif