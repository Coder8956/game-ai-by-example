//==============================================================================================
//【文件说明】CrudeTimer.cpp —— CrudeTimer 类的实现(单例的"唯一对象"就在这里诞生)
//
//【这个文件是干什么的?】
//  头文件 CrudeTimer.h 里只声明了 Instance(),真正的实现在本文件。
//  Instance() 的职责:保证全程序只有一个计时器对象,并把它的指针交给调用者。
//
//【谁在使用本文件?】谁包含 CrudeTimer.h,谁就用到这里的 Instance()(详见头文件)。
//
//【本文件包含了谁?】
//  CrudeTimer.h —— 自己的类声明(要先知道类长什么样,才能写它的成员函数)。
//==============================================================================================
#include "CrudeTimer.h"


//--------------------------------------------------------------------------------
// CrudeTimer::Instance() —— 单例取对象入口的实现。
//   CrudeTimer* :返回值类型是"指向 CrudeTimer 的指针";
//   CrudeTimer:::作用域解析符,说明这个 Instance 属于 CrudeTimer 类。
// 原理(C++ 局部静态变量实现的单例,又称 Meyers 单例):
//   函数内部写一个 static 局部变量 instance —— 它在程序运行期间只"出生"一次,
//   以后每次调用 Instance() 都返回同一个它。于是全程序自然只有一个计时器。
//--------------------------------------------------------------------------------
CrudeTimer* CrudeTimer::Instance()
{
  static CrudeTimer instance;

  // &instance:& 是"取地址符",取出上面那个唯一静态对象的内存地址,以指针形式返回。
  return &instance;
}