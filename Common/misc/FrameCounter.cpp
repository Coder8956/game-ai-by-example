//==============================================================================================
//【文件说明】FrameCounter.cpp —— 帧计数器的单例实现
//  Instance() 用函数内静态局部变量保证全程序只有一个帧计数器。
//==============================================================================================
#include "framecounter.h"


  // 单例经典写法:第一次调用时创建静态对象,之后返回其地址。
FrameCounter* FrameCounter::Instance()
{
  static FrameCounter instance;

  return &instance;
}